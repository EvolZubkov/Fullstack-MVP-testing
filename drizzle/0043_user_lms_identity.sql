-- PRD-54 BR-54-25, BR-54-28, BR-54-31 (решения владельца 2026-09-25): поля учётной записи, по
-- которым прохождение из LMS связывается с человеком.
--
-- `lms_learner_id` — идентификатор обучающегося в LMS (`cmi.learner_id`). Отдельное поле, а НЕ
-- `external_key`: источники дают разные идентификаторы одного человека, и оба существуют
-- одновременно. В рантайме LMS сообщает `learner_id` и не знает табельного кода; в выгрузке есть
-- код и нет `learner_id`. Поле «что-нибудь одно» превратило бы связывание в лотерею —
-- заполнивший его не знал бы, какой источник включил, а какой выключил.
--
-- `organization`, `unit`, `position` — те же поля, из которых считается псевдоним участника
-- выгрузки. Нужны, чтобы система могла посчитать для СВОЕГО пользователя тот же ключ, что внешний
-- обезличиватель считает для строки файла.
--
-- Все четыре необязательны: их отсутствие значит лишь, что связывание пойдёт другим путём из
-- порядка BR-54-33 или не пойдёт вовсе. Ни одно не блокирует создание пользователя.
