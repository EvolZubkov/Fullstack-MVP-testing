-- PRD-66, этап Э1: подготовка наблюдений психометрики. Три аддитивные колонки.
--
-- `lms_import_batches.rows_unmatched` (FR-11) — сколько взаимодействий файла не удалось
-- сопоставить с заданием теста. Доля потерь решает, можно ли вообще считать партию, и
-- читателю она нужна числом рядом с партией, а не строкой в журнале предупреждений.
--
-- `lms_import_batches.counted` (FR-12) — участвует ли партия в статистике. Снятие с
-- учёта убирает партию из выборки, НЕ удаляя строк: партия с испорченной выгрузки
-- перестаёт искажать числа, а данные остаются для разбора. Умолчание `true` — все уже
-- загруженные партии продолжают считаться.
--
-- `questions.psycho_hash` (FR-09a) — отпечаток СОДЕРЖАНИЯ задания, по которому ответы
-- собираются в серию наблюдений. Правка задания делает ответы до и после
-- психометрически разными пунктами: трудность, снятая со старой формулировки, ничего не
-- говорит о новой, и смешивать их в одну статистику нельзя.
--
-- Своя колонка, а НЕ `content_hash`: последнюю сравнивает PRD-15 — цена задания внутри
-- теста пришпилена к редакции через `test_question_scoring.pinned_content_hash`, и смена
-- правила расчёта разом пометила бы устаревшими все пины цен на каждом тесте. Две
-- колонки отвечают на разные вопросы и должны расходиться свободно.
--
-- Nullable и без бэкфилла в SQL: отпечаток считает `shared/questions/psycho-hash`
-- (канонизация ключей, пары «текст варианта -> верность»), и повторять это правило на
-- SQL значило бы завести вторую реализацию, которая разойдётся с первой на первой же
-- правке. Существующие строки заполняет `npm run psycho:backfill` той же функцией.
-- Строка без отпечатка — серия «версия неизвестна» (FR-09c), это решение ОВ-04.
ALTER TABLE "lms_import_batches" ADD COLUMN "rows_unmatched" integer DEFAULT 0 NOT NULL;--> statement-breakpoint
ALTER TABLE "lms_import_batches" ADD COLUMN "counted" boolean DEFAULT true NOT NULL;--> statement-breakpoint
ALTER TABLE "questions" ADD COLUMN "psycho_hash" text;
