-- PRD-56, уточнение модели (решение владельца 2026-09-25): сохранённый ФИЛЬТР реестра и
-- СРЕЗ аналитики разводятся.
--
-- Условия у них одного языка, но вопросы разные. Фильтр отвечает «покажи эти прохождения» и
-- может охватывать РАЗНЫЕ тесты. Срез отвечает «вот выборка ОДНОГО теста, считай по ней»:
-- средние, пороги и сравнение поверх нескольких тестов не значат ничего (FR-07e), поэтому
-- срез с двумя тестами сохранить нельзя — раньше он сохранялся, молча забирая первый из них.
--
-- Одна колонка, а не вторая таблица: условия у обеих ролей — тот же словарь, и две таблицы
-- под одни данные разошлись бы на первой же новой оси отбора. Умолчание `slice` оставляет
-- существующие записи там, где они есть: все они создавались как срезы.
ALTER TABLE "analytics_slices" ADD COLUMN "kind" text DEFAULT 'slice' NOT NULL;
