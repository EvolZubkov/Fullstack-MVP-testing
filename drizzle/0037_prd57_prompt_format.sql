-- PRD-57 §4.3: формат, в котором автор написал текст задания.
--
-- Аддитивно: у всех существующих заданий формат `markdown`, и это ровно их сегодняшнее
-- поведение — текст читается как подмножество разметки. Сам текст не мигрируется: колонка
-- `prompt` остаётся исходником в любом формате, а хеш содержимого формата не знает и потому
-- не сдвигается ни у одного вопроса.
ALTER TABLE "questions" ADD COLUMN "prompt_format" text DEFAULT 'markdown' NOT NULL;