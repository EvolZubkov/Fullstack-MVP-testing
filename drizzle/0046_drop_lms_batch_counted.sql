-- Снятие переключателя «В расчётах» у загрузок выгрузок LMS (PRD-66 FR-12 отменён владельцем
-- 2026-10-02: «повышаем цену ошибки»). Сомнительную выгрузку теперь откатывают целиком и
-- загружают заново, а не держат в базе невидимой для расчётов.
--
-- РАЗРУШАЮЩАЯ миграция. Колонка исчезает вместе со смыслом партий, снятых с учёта: после неё
-- такая партия молча вернулась бы в выборку. Поэтому сначала предохранитель — если хоть одна
-- партия снята с учёта, миграция падает, ничего не изменив. Такие партии откатывают руками
-- (кнопкой «Откатить» в шаге загрузки выгрузок LMS) и только потом выкатывают.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM "lms_import_batches" WHERE "counted" = false) THEN
    RAISE EXCEPTION 'lms_import_batches: есть загрузки, снятые с учёта (counted = false). Откатите их до применения 0046.';
  END IF;
END $$;--> statement-breakpoint
ALTER TABLE "lms_import_batches" DROP COLUMN "counted";
