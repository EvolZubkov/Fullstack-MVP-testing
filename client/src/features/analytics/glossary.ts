export type GlossaryKey = keyof typeof GLOSSARY;

/**
 * Пояснение к «мало данных»: с какого числа наблюдений величина появится и сколько собрано.
 *
 * @param need порог наблюдений
 * @param have сколько собрано
 * @returns текст подсказки
 */
export function insufficientHint(need: number, have: number): string {
  return `Число появится с ${need} наблюдений: на меньшей выборке оно случайно. Собрано ${have}.`;
}
