/**
 * @module features/analytics/test/__tests__/psychometrics-format
 * @description PRD-66: как психометрическое число печатается человеку.
 *
 * Форматтер общий у двух экранов — вкладки «Качество вопросов» и таблицы «Вопросы» (FR-02,
 * FR-03), — поэтому его правила стерегутся отдельно от них: разойдясь, они дали бы одно и то
 * же число в двух написаниях.
 */
import { describe, expect, it } from "vitest";

import { num } from "../psychometrics-format";

describe("num", () => {
  it("печатает число с запятой и двумя знаками", () => {
    expect(num(0.413)).toBe("0,41");
  });

  it("у отрицательной величины ставит МИНУС, а не дефис", () => {
    // Дефис в колонке чисел читается как перенос или прочерк, а знак величины — главное в
    // дискриминативности: именно минус отличает испорченный ключ от рабочего задания.
    expect(num(-0.83)).toBe("−0,83");
  });

  it("отсутствующую величину печатает прочерком, а не нулём", () => {
    expect(num(null)).toBe("—");
  });

  it("знаков после запятой может быть больше", () => {
    expect(num(0.4137, 3)).toBe("0,414");
  });
});
