/**
 * @module features/analytics/test/psychometrics-format
 * @description PRD-66: как психометрическое число печатается человеку.
 *
 * Живёт отдельным модулем, потому что одни и те же величины показываются на ДВУХ экранах —
 * во вкладке «Качество вопросов» и в строке таблицы «Вопросы» (FR-02, FR-03). Копия форматтера
 * разошлась бы на первой же правке: «0,41» на одном экране и «0.41» на другом читаются как
 * два разных числа.
 */

/** Наблюдений, начиная с которых коэффициент вообще выводится (движок: COEFFICIENT_MIN). */
export const COEFFICIENT_MIN = 30;

/**
 * Число с запятой и двумя знаками; прочерк там, где величины нет.
 *
 * Знак минуса — типографский (U+2212), а не дефис: в колонке чисел дефис читается как
 * перенос или как прочерк «величины нет», а у дискриминативности знак — главное, что о ней
 * сказано. Именно минус отличает испорченный ключ от рабочего задания.
 */
export function num(value: number | null, digits = 2): string {
  return value === null ? "—" : value.toFixed(digits).replace(".", ",").replace("-", "−");
}
