/**
 * Число с запятой и двумя знаками; прочерк там, где величины нет.
 *
 * Знак минуса — типографский (U+2212), а не дефис: в колонке чисел дефис читается как
 * перенос или как прочерк «величины нет», а у дискриминативности знак — главное, что о ней
 * сказано. Именно минус отличает испорченный ключ от рабочего задания.
 */
export function num(value: number | null, digits = 2): string {
  return value === null ? "—" : value.toFixed(digits).replace(".", ",").replace("-", "−");
}
