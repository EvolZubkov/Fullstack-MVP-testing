/**
 * @module shared/psychometrics/__tests__/stats
 *
 * Эталонные значения посчитаны вручную (AC-01): движок, проверенный сам собой, доказывает
 * только то, что он не изменился.
 */
import { describe, expect, it } from "vitest";

import { mean, pearson, standardDeviation, variance } from "../stats";

describe("mean", () => {
  it("считает среднее", () => {
    expect(mean([1, 2, 3, 4])).toBe(2.5);
  });

  it("на пустом ряду возвращает отсутствие величины, а не ноль", () => {
    // Ноль — это утверждение «среднее равно нулю». Пустая выборка его не даёт.
    expect(mean([])).toBeNull();
  });
});

describe("variance", () => {
  it("считает ВЫБОРОЧНУЮ дисперсию, деля на n - 1", () => {
    // [1,1,0,0]: среднее 0,5; сумма квадратов отклонений 1; делитель 3.
    expect(variance([1, 1, 0, 0])).toBeCloseTo(1 / 3, 12);
  });

  it("у ряда без разброса дисперсия ноль — это факт, а не пустота", () => {
    expect(variance([1, 1, 1, 1])).toBe(0);
  });

  it("по одному наблюдению разброс не определён", () => {
    // Не «нулевой разброс»: по одному человеку нельзя сказать, насколько люди различаются.
    expect(variance([0.5])).toBeNull();
  });
});

describe("standardDeviation", () => {
  it("есть корень из дисперсии", () => {
    expect(standardDeviation([4, 3, 2, 1])).toBeCloseTo(Math.sqrt(5 / 3), 12);
  });
});

describe("pearson", () => {
  it("совпадает с ручным счётом на эталонном наборе", () => {
    // x = доля балла задания, y = доля балла на остальных заданиях формы.
    // Σdx·dy = 0,25; Σdx² = 0,75; Σdy² = 0,3055(5) → r = 0,25 / √0,229166… = 0,52223…
    const x = [1, 1, 1, 0];
    const y = [1, 2 / 3, 1 / 3, 1 / 3];
    expect(pearson(x, y)).toBeCloseTo(0.5222329678, 9);
  });

  it("полная прямая связь даёт единицу, обратная — минус единицу", () => {
    expect(pearson([1, 2, 3], [2, 4, 6])).toBeCloseTo(1, 12);
    expect(pearson([1, 2, 3], [6, 4, 2])).toBeCloseTo(-1, 12);
  });

  it("ряд без разброса корреляции не имеет — это не нулевая связь", () => {
    // Задание, которое решили все, никого не различает. Списать его в «не дискриминирует»
    // нельзя: оно просто ничего не измеряет, и это разные утверждения.
    expect(pearson([1, 1, 1, 1], [1, 2, 3, 4])).toBeNull();
  });

  it("ряды разной длины — ошибка вызывающего, а не нулевая корреляция", () => {
    expect(pearson([1, 2, 3], [1, 2])).toBeNull();
  });
});
