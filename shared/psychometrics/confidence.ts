/**
 * @module shared/psychometrics/confidence
 *
 * Уровень доверия к числу по объёму выборки (FR-04, FR-23, FR-38).
 *
 * На экране сосуществуют ДВА порога, и это главный источник недоразумений. Описательные
 * величины — трудность, частоты, пропуски, экспозиция, время — живут при пороге наблюдений
 * инстанса (`analytics.minObservations`, сегодня 10): трудность заменила долю верных на вкладке
 * «Вопросы», и поднять ей порог значило бы отнять у автора число, которое он видел раньше.
 * Коэффициенты — дискриминативность, надёжность, ошибка измерения, корреляции — требуют 30 и
 * 100 наблюдений: на пятнадцати респондентах корреляция скачет от выборки к выборке сильнее,
 * чем от качества задания.
 *
 * Поэтому у задания с двенадцатью наблюдениями трудность видна, а дискриминативность — нет, и
 * экран обязан называть, какой порог к какому числу применён (FR-38a).
 */

/** Насколько можно опереться на число при таком объёме наблюдений. */
export type ConfidenceLevel =
  /** Меньше порога: число не выводится вовсе — «недостаточно данных» (FR-44). */
  | "insufficient"
  /** Порог взят, но выборка мала: число выводится с оговоркой «ориентировочно». */
  | "tentative"
  /** Выборка достаточна: число выводится как есть. */
  | "reliable";

/** Наблюдений, начиная с которых коэффициент вообще выводится. */
export const COEFFICIENT_MIN = 30;
/** Наблюдений, начиная с которых коэффициент считается надёжным. */
export const COEFFICIENT_RELIABLE = 100;

/**
 * Уровень доверия к КОЭФФИЦИЕНТУ (дискриминативность, альфа, SEM, корреляции).
 *
 * @param n число наблюдений, на которых посчитан коэффициент
 */
export function coefficientConfidence(n: number): ConfidenceLevel {
  if (n < COEFFICIENT_MIN) return "insufficient";
  return n < COEFFICIENT_RELIABLE ? "tentative" : "reliable";
}

/**
 * Уровень доверия к ОПИСАТЕЛЬНОЙ величине (трудность, частоты, время).
 *
 * Порог приходит из настройки инстанса, а не зашит здесь: он общий с остальной аналитикой, и
 * второе его значение в психометрике означало бы, что одно и то же число на двух вкладках
 * появляется при разном объёме данных.
 *
 * @param n число наблюдений
 * @param minObservations порог инстанса (`analytics.minObservations`)
 */
export function descriptiveConfidence(n: number, minObservations: number): ConfidenceLevel {
  if (n < minObservations) return "insufficient";
  // У описательных величин «ориентировочно» отдельной ступенью не выделяется: порог инстанса и
  // есть граница, за которой автор привык этим числам верить.
  return "reliable";
}
