/**
 * @module shared/report/paginate
 *
 * Где кончается страница отчёта — единственное решение постраничной раскладки, вынутое
 * из конвейера экспорта ({@link module:shared/report/export-pdf}) отдельным чистым модулем.
 *
 * ПОЧЕМУ ОТДЕЛЬНО. Конвейер живёт в браузере: он рисует макет, растеризует его и пишет
 * PDF. Правило страниц к браузеру отношения не имеет — это арифметика над измеренными
 * координатами, и в отрыве от DOM она и проверяется, и читается. Обратная сторона того же
 * разделения: модуль НИЧЕГО не измеряет сам. Координаты приходят готовыми, потому что
 * знать их может только тот, кто держит отрисованную страницу.
 *
 * ПРАВИЛО. Разрыв проходит между блоками верхнего уровня — карточками отчёта и строками
 * его шапки. Карточка, не поместившаяся в остаток страницы, уходит на следующую целиком:
 * документ читают глазами, и «Ваш результат», разрезанный посередине уровня, — это не
 * страница, а брак. Единственное исключение — карточка, которая выше страницы сама по
 * себе (длинное толкование показателя): её незачем переносить, ей всё равно не хватит
 * места, поэтому она отдаётся как есть, и конвейер режет её растр по высоте страницы.
 *
 * ПРИНУДИТЕЛЬНЫЙ РАЗРЫВ отменяет всё вышесказанное там, где он стоит: верстальщик шаблона
 * объявляет в макете отчёта узел `[data-page-break]`, и лист обязан кончиться на нём,
 * сколько бы места ни осталось. Машина знает, что помещается на лист, но не знает, что
 * документ читается разделами, — это знает автор шаблона (спека
 * `docs/specs/2026-08-13-report-page-break-design.md`).
 *
 * Чистый модуль: ни DOM, ни Node.
 */

/** Вертикальные границы одного блока верхнего уровня, в пикселях от верха документа. */
export interface ReportBlockBox {
  top: number;
  bottom: number;
}

/** Одна страница: какие блоки на ней, с какой высоты документа она начинается. */
export interface ReportPagePlan {
  /** Индексы блоков в исходном порядке. */
  blocks: number[];
  /** Смещение страницы от верха документа — по нему обрезается снимок. */
  offset: number;
  /**
   * Высота страницы: обычно ровно полезная высота A4, но у страницы с блоком-переростком —
   * высота этого блока. Конвейер по ней решает, резать ли снимок дальше.
   */
  height: number;
}

/** Кусок листа: откуда и сколько взять от снимка страницы. */
export interface ReportSlice {
  top: number;
  height: number;
}

/**
 * Минимальная высота куска. Страховка от зацикливания: безопасная линия, совпавшая с
 * верхом куска, не считается разрезом.
 */
const MIN_SLICE_PX = 1;

/**
 * Насколько близко к краю листа должна лежать граница вложенного блока, чтобы разрез
 * прошёл по ней, а не по строке. Доля высоты листа.
 */
const BLOCK_PREFERENCE_ZONE = 0.15;

/**
 * Наименьшая доля листа, которую не стыдно отдать под хвост разрезанного блока.
 *
 * Полный лист плюс огрызок в полторы сотни пикселей — это и есть та «почти пустая
 * страница», ради которой всё затевалось. Дешевле недобрать немного на предыдущем листе:
 * два умеренных листа читаются лучше, чем полный и почти пустой.
 */
const MIN_TAIL_SHARE = 0.25;

/** Подсказки хоста о том, где резать приятнее. */
export interface SliceOptions {
  /**
   * Границы вложенных блоков — низ карточки показателя, шкалы, абзаца рекомендаций.
   * Разрез по ним оставляет блок целым, поэтому вблизи края листа они выигрывают у
   * строки. Хост собирает их тем же обходом, что и безопасные линии.
   */
  blockLines?: number[];
  /**
   * ПРИНУДИТЕЛЬНЫЕ разрывы: ординаты, по которым лист обязан кончиться, — верхние границы
   * узлов `[data-page-break]`, объявленных в макете отчёта.
   *
   * Это приказ верстальщика шаблона, а не подсказка: он сильнее и правила «карточку не
   * рвём», и правила висячей строки, и предпочтения крупных границ. Линия у самого верха
   * или у самого низа содержимого молча отбрасывается — пустых листов механика не даёт.
   */
  forcedLines?: number[];
}

/**
 * Высота строки, оценённая по безопасным линиям.
 *
 * Считается медианой расстояний между соседними линиями, а не средним: список несёт и
 * низы вложенных элементов, поэтому в нём есть единичные большие разрывы, которые
 * среднее вытянуло бы, а медиана игнорирует. Пустой или вырожденный список даёт `0` —
 * тогда правило висячей строки просто не применяется.
 */
function lineStep(safeLines: number[]): number {
  const sorted = [...new Set(safeLines)].sort((a, b) => a - b);
  const gaps: number[] = [];
  for (let i = 1; i < sorted.length; i += 1) {
    const gap = sorted[i] - sorted[i - 1];
    if (gap > 0) gaps.push(gap);
  }
  if (!gaps.length) return 0;
  gaps.sort((a, b) => a - b);
  return gaps[Math.floor(gaps.length / 2)];
}

/**
 * Разрезать блок, который выше страницы, ПО БЕЗОПАСНЫМ ЛИНИЯМ.
 *
 * Безопасная линия — низ визуальной строки текста либо низ вложенного элемента; их
 * измеряет хост, потому что знать, где браузер перенёс строку, может только браузер.
 * Разрез проходит по последней такой линии, помещающейся на лист: строка, разрезанная
 * пополам, нечитаема на обеих половинах — верхняя половина букв на одном листе, нижняя на
 * другом, и это ХУЖЕ, чем недобранные сантиметры внизу листа.
 *
 * Если безопасной линии на лист не нашлось (её и не может быть, когда одна строка выше
 * страницы, или среда не считает раскладку), режется по высоте листа: напечатать
 * что-нибудь лучше, чем не напечатать ничего.
 *
 * ПРИНУДИТЕЛЬНЫЙ РАЗРЫВ (`SliceOptions.forcedLines`) старше высоты листа: содержимое сперва
 * делится по нему на разделы, и уже каждый раздел режется по строкам. Поэтому короткий блок
 * с разрывом внутри тоже делится, хотя по высоте делить его было бы не за чем.
 *
 * @param safeLines Ординаты безопасных линий от верха блока, в любом порядке.
 * @param contentHeight Полная высота блока.
 * @param pageHeight Высота листа в тех же единицах.
 */
export function sliceBySafeLines(
  safeLines: number[],
  contentHeight: number,
  pageHeight: number,
  opts: SliceOptions = {},
): ReportSlice[] {
  if (!(pageHeight > 0)) return [{ top: 0, height: contentHeight }];
  // ПРИНУДИТЕЛЬНЫЕ РАЗРЫВЫ делят содержимое на разделы, и уже каждый раздел режется по
  // высоте листа. Линия у самого верха или у самого низа содержимого отбрасывается: за ней
  // нечего печатать, а лист получился бы пустым.
  const forced = [...new Set(opts.forcedLines ?? [])]
    .filter((line) => line > MIN_SLICE_PX && line < contentHeight - MIN_SLICE_PX)
    .sort((a, b) => a - b);
  if (!forced.length && contentHeight <= pageHeight) {
    return [{ top: 0, height: contentHeight }];
  }
  // Хвост обязан нести И не меньше двух строк (иначе строка висит одна), И заметную долю
  // листа (иначе страница выходит почти пустой). Оба порога — про одно и то же: последний
  // лист документа должен выглядеть страницей, а не обрезком.
  const minTail = Math.max(2 * lineStep(safeLines), pageHeight * MIN_TAIL_SHARE);

  const slices: ReportSlice[] = [];
  let from = 0;
  for (const to of [...forced, contentHeight]) {
    if (to - from <= MIN_SLICE_PX) continue;
    slices.push(...sliceSection(safeLines, from, to, pageHeight, opts, minTail));
    from = to;
  }
  return slices.length ? slices : [{ top: 0, height: contentHeight }];
}

/**
 * Разрезать ОДИН раздел — участок содержимого между принудительными разрывами (а без них —
 * весь блок целиком) — по безопасным линиям и высоте листа.
 *
 * Правило висячей строки применяется В ПРЕДЕЛАХ раздела: следующий раздел начинается с
 * нового листа по требованию верстальщика, поэтому дотягивать до него хвост нельзя.
 */
function sliceSection(
  safeLines: number[],
  from: number,
  to: number,
  pageHeight: number,
  opts: SliceOptions,
  minTail: number,
): ReportSlice[] {
  const blockLines = opts.blockLines ?? [];
  const zone = pageHeight * BLOCK_PREFERENCE_ZONE;
  const slices: ReportSlice[] = [];
  let top = from;
  while (to - top > pageHeight) {
    const limit = top + pageHeight;
    let cut = 0;
    for (const line of safeLines) {
      if (line > top + MIN_SLICE_PX && line <= limit && line > cut) cut = line;
    }
    // Граница вложенного блока БЛИЗКО к краю листа выигрывает у строки: потерять
    // десяток пикселей бумаги дешевле, чем разорвать карточку показателя пополам.
    // Далёкая граница проигрывает — за целостность блока, который всё равно будет
    // разрезан следующим листом, полстраницы не отдают.
    let preferred = 0;
    for (const line of blockLines) {
      if (line > top + MIN_SLICE_PX && line <= limit && line >= limit - zone && line > preferred) {
        preferred = line;
      }
    }
    if (preferred) cut = preferred;
    if (!cut) cut = limit;
    slices.push({ top, height: cut - top });
    top = cut;
  }

  // ВИСЯЧАЯ СТРОКА: хвост в одну строку — не страница, а брак вёрстки. Если остаток
  // меньше двух строк, последний разрез отступает назад по безопасной линии, отдавая
  // хвосту достаточно текста. Отступать некуда (нет подходящей линии) — печатаем как
  // есть: напечатать что-нибудь лучше, чем не напечатать ничего.
  const tail = to - top;
  if (slices.length && minTail > 0 && tail < minTail) {
    let moved = 0;
    for (const line of safeLines) {
      if (line > slices[slices.length - 1].top + MIN_SLICE_PX && to - line >= minTail && line > moved) {
        moved = line;
      }
    }
    if (moved) {
      const last = slices[slices.length - 1];
      last.height = moved - last.top;
      top = moved;
    }
  }
  slices.push({ top, height: to - top });
  return slices;
}

/**
 * Разложить блоки отчёта по страницам.
 *
 * @param boxes Границы блоков верхнего уровня, В ПОРЯДКЕ документа, измеренные хостом.
 * @param usableHeight Полезная высота страницы в тех же пикселях (высота A4 за вычетом
 *   полей страницы отчёта). Ноль или отрицательная величина означает «разделить нечем» —
 *   так приходит из среды, которая раскладку не считает (jsdom в тестах), и тогда
 *   документ остаётся одной страницей, каким был до постраничной выдачи.
 * @returns План страниц; пустой список для пустого входа.
 */
export function paginateBlocks(boxes: ReportBlockBox[], usableHeight: number): ReportPagePlan[] {
  if (!boxes.length) return [];
  const contentBottom = Math.max(...boxes.map((b) => b.bottom));
  if (!(usableHeight > 0)) {
    return [{ blocks: boxes.map((_, i) => i), offset: 0, height: contentBottom }];
  }

  const pages: ReportPagePlan[] = [];
  let current: number[] = [];
  let offset = 0;

  /** Закрыть набранную страницу: её высота — полная, кроме страницы с переростком. */
  const flush = (bottom: number) => {
    pages.push({ blocks: current, offset, height: Math.max(usableHeight, bottom - offset) });
  };

  boxes.forEach((box, i) => {
    // Переносится только та карточка, которой новый лист ПОМОЖЕТ, — та, что целиком на
    // лист помещается. Карточке выше листа он не поможет ничем: разрез внутри неё всё
    // равно неизбежен, а перенос стоил остатка текущего листа — шапка отчёта и семь сотен
    // пикселей пустой бумаги. Поэтому переросток начинается там, где стоит.
    const fitsOnPage = box.bottom - box.top <= usableHeight;
    // Первый блок страницы кладётся безусловно: переносить его некуда, а если он выше
    // страницы — это и есть переросток, который дальше режет конвейер.
    if (current.length > 0 && box.bottom - offset > usableHeight && fitsOnPage) {
      flush(boxes[current[current.length - 1]].bottom);
      current = [];
      offset = box.top;
    }
    current.push(i);
  });
  flush(boxes[current[current.length - 1]].bottom);

  return pages;
}
