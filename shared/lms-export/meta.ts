/**
 * @module shared/lms-export/meta
 * @description PRD-56 FR-19a: служебные блоки выгрузки, которыми пакет сообщает о САМОМ
 * прохождении — версию публикации и выданные варианты; PRD-54 BR-54-35 — метку регистрации.
 *
 * Сегодня версия публикации есть только у веб-попытки (`attempts.snapshot_id`): в пакет она не
 * уезжала, в отчёте LMS её не было, и разрез по версиям был слеп ровно к тем прохождениям, ради
 * которых пакет и собирали. Вариант выдачи (PRD-17 `formId`) не доезжал по той же причине.
 *
 * Канал не новый: `meta_response_format` (`./response-codec`) уже ездит этим способом, а разбор
 * пропускает любой блок с префиксом `meta_` мимо «неопознанных колонок». Здесь живут ТОЛЬКО
 * идентификаторы блоков и кодирование их значений: половину, которая пишет, держит рантайм
 * пакета (`server/scorm/template/app/render/resultsPage.js`) обычным ES5 без импортов, поэтому
 * совпадение литералов с этими константами стережёт зеркальный тест `tests/scorm-meta-blocks`.
 */

/**
 * Идентификатор служебного блока с номером версии публикации (`test_snapshots.version`).
 *
 * Номер, а не идентификатор снимка: он уникален внутри теста, читается человеком в отчёте и не
 * выносит наружу внутренних ключей. Отсутствие блока в выгрузке означает «пакет собран раньше
 * этой работы» — такое прохождение идёт в строку «Версия не указана».
 */
export const TEST_VERSION_INTERACTION_ID = "meta_test_version";

/**
 * Идентификатор служебного блока с выданными вариантами (PRD-17 `formId`).
 *
 * Вариант — свойство РАЗДЕЛА, поэтому их может быть несколько на одно прохождение. В ячейку
 * едет список идентификаторов; тему каждого из них сервер восстанавливает по набору форм теста,
 * а не по порядку в строке — разделы переставляют, и позиционный смысл разошёлся бы молча.
 */
export const VARIANT_INTERACTION_ID = "meta_variant";

/**
 * Идентификатор служебного блока с меткой регистрации SCO (PRD-54 раздел 7.1b, BR-54-35).
 *
 * Метка одна на РЕГИСТРАЦИЮ — то, чему в отчёте LMS соответствует одна строка, — а не на попытку:
 * внутри регистрации пакет проводит несколько попыток и отдаёт в LMS одну. По метке импорт
 * различает две строки одного участника за одну дату, которые дата без времени различить не может.
 * Отсутствие блока — пакет собран раньше; тогда строки различает отпечаток содержимого.
 */
export const REGISTRATION_INTERACTION_ID = "meta_registration";

/** Разделитель списка вариантов. Идентификаторы формы — uuid, поэтому не встречается в них. */
const SEPARATOR = ";";

/** Список выданных вариантов одной строкой для ячейки выгрузки. */
export function encodeVariantForms(formIds: readonly string[]): string {
  return formIds
    .map((id) => String(id ?? "").trim())
    .filter((id) => id !== "")
    .join(SEPARATOR);
}

/** Разбор ячейки со списком вариантов. Пустая ячейка — пустой список, а не список из пустоты. */
export function decodeVariantForms(raw: string | null | undefined): string[] {
  return String(raw ?? "")
    .split(SEPARATOR)
    .map((id) => id.trim())
    .filter((id) => id !== "");
}

/**
 * Номер версии публикации из ячейки выгрузки.
 *
 * `null` — версия НЕ СООБЩЕНА: пустая ячейка, мусор, ноль или дробь. Ни одно из этих значений
 * не превращается в номер: приписать такое прохождение текущей версии значит сделать разрез по
 * версиям бесполезным ровно там, где он и нужен.
 */
export function parseTestVersion(raw: string | null | undefined): number | null {
  const value = String(raw ?? "").trim();
  if (value === "") return null;
  const n = Number(value);
  return Number.isInteger(n) && n >= 1 ? n : null;
}
