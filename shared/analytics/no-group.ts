/**
 * @module shared/analytics/no-group
 * @description Значение «Без группы» в отборе аналитики по группам.
 *
 * Отбор по группам находил только прохождения участников, состоящих в выбранных группах, и
 * прохождения людей вне групп отобрать было нельзя вовсе (замечание владельца 2026-10-04). Их
 * много: внешние участники, прохождения из LMS без группы загрузки, люди, которых ещё не
 * распределили.
 *
 * «Без группы» — особое значение в том же списке групп, а не отдельное условие: его можно выбрать
 * вместе с обычными группами («Отдел продаж или без группы»), и оно живёт в адресе страницы так
 * же, как они (`groupId=none`). Идентификаторы групп — UUID, и с ними значение не пересекается.
 *
 * Что значит «без группы»: участник не состоит ни в одной группе; у прохождения из LMS — к тому
 * же не задана группа загрузки (партия импорта, назначение пакета).
 */

/** Значение «Без группы» в списке `groupIds`. */
export const NO_GROUP_ID = "none";

/** Подпись значения в списке и в чипе фильтра. */
export const NO_GROUP_LABEL = "Без группы";

/**
 * Разделить отбор по группам на настоящие группы и признак «без группы».
 *
 * @param groupIds выбранные значения
 * @returns настоящие группы и выбрано ли «Без группы»
 */
export function splitGroupFilter(groupIds: readonly string[] | undefined): { groups: string[]; none: boolean } {
  const list = groupIds ?? [];
  return { groups: list.filter(id => id !== NO_GROUP_ID), none: list.includes(NO_GROUP_ID) };
}
