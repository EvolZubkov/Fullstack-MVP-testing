/**
 * @module shared/draw/expected-exposure
 *
 * PRD-55 (FR-33): ОЖИДАЕМАЯ экспозиция — какую долю участников увидит каждое задание темы при
 * нынешних настройках выдачи.
 *
 * Отличается от накопленной (`question_exposure`) тем, что не требует ни одного прохождения:
 * она следует из размера банка и объёма выдачи, поэтому её видно на пустом тесте, в момент
 * настройки — то есть тогда, когда её ещё можно исправить. Накопленная отвечает на «что уже
 * произошло», эта — на «что произойдёт».
 *
 * Чистая функция, потому что нужна трём местам одинаково: строке темы в редакторе, сводке
 * свёрнутой темы и окну сборки пакета. Второй копии формулы в проекте быть не должно — разойдясь,
 * они показали бы автору два разных числа про одно и то же.
 */

/** Доля, начиная с которой выработка банка считается проблемой и требует внимания автора. */
export const EXPOSURE_WARN_THRESHOLD = 70;

export interface ExpectedExposureInput {
  /** Сколько заданий темы уходит в тест. */
  drawCount: number;
  /** Сколько заданий в банке темы. */
  poolSize: number;
}

export interface ExpectedExposure {
  /** Доля участников, которые увидят каждое задание темы, в процентах. */
  percent: number;
  /** Тон сообщения: предупреждение о выработке банка либо обычное сообщение. */
  tone: "warning" | "info";
}

/**
 * Ожидаемая экспозиция задания темы.
 *
 * @param input - Объём выдачи и размер банка темы.
 * @returns Доля и тон, либо `null`, когда считать не из чего (пустой банк или не заданная выдача).
 */
export function expectedExposure(input: ExpectedExposureInput): ExpectedExposure | null {
  const { drawCount, poolSize } = input;
  if (!Number.isFinite(drawCount) || !Number.isFinite(poolSize)) return null;
  if (drawCount <= 0 || poolSize <= 0) return null;

  // Подрезки до 100% нет намеренно: редактор выдачу больше банка не даст, но книга Excel и
  // перенос теста — могут, и такое расхождение настроек с банком автор должен увидеть, а не
  // получить благополучную сотню.
  const percent = Math.round((drawCount / poolSize) * 100);
  return { percent, tone: percent >= EXPOSURE_WARN_THRESHOLD ? "warning" : "info" };
}
