/**
 * @module shared/draw/exposure
 *
 * PRD-55: вес задания по накопленной экспозиции и взвешенный отбор без возвращения.
 *
 * Шкала СРАВНИТЕЛЬНАЯ и считается внутри пула, из которого идёт отбор (страта квоты PRD-11 либо
 * остаток раздела): она отвечает на вопрос «какое из этих заданий выдавалось реже», а не «много
 * ли это — 300 выдач». Поэтому банк, выданный целиком и равномерно, поправкой не искажается — в
 * нём все счётчики равны.
 *
 * Предел отношения весов — системная константа, а не настройка (FR-13). Без него вес вида
 * «единица делить на число выдач» вырождается в почти детерминированный обход банка: свежее
 * задание выпадает первым почти наверняка, выдача становится предсказуемой, и на месте одной
 * бреши открывается другая.
 *
 * Модуль ЧИСТЫЙ: ни базы, ни времени, ни глобального состояния внутри. Плейн-JS двойник живёт в
 * `server/scorm/assets/app.js` и держится в парности golden-тестом `tests/exposure-port.test.ts`.
 */

/** Предельное отношение вероятностей между самым свежим и самым горячим заданием пула (FR-13). */
export const EXPOSURE_WEIGHT_RATIO = 4;

/**
 * Веса заданий пула по счётчикам выдач за окно (FR-12).
 *
 * Самое горячее задание пула получает вес `1`, самое свежее — `EXPOSURE_WEIGHT_RATIO`, остальные
 * раскладываются между ними линейно. Отсутствие задания в `counts` означает ноль выдач: «нет
 * ключа» и «ноль» здесь одно и то же, поэтому карту счётчиков можно отдавать разреженной.
 *
 * @param poolIds - Идентификаторы заданий пула, из которого пойдёт отбор.
 * @param counts - Число выдач за окно по заданиям; разреженная карта допустима.
 * @returns Карта «задание -> вес» в пределах [1, EXPOSURE_WEIGHT_RATIO].
 */
export function computeWeights(
  poolIds: string[],
  counts: Map<string, number>,
): Map<string, number> {
  const weights = new Map<string, number>();
  if (poolIds.length === 0) return weights;

  const values = poolIds.map((id) => counts.get(id) ?? 0);
  let min = values[0];
  let max = values[0];
  for (const v of values) {
    if (v < min) min = v;
    if (v > max) max = v;
  }

  // Сравнивать нечего — ни данных, ни разброса. Это и есть механизм деградации (FR-17):
  // все веса равны, и отбор становится сегодняшним равномерным.
  if (max === min) {
    for (const id of poolIds) weights.set(id, 1);
    return weights;
  }

  const span = max - min;
  for (let i = 0; i < poolIds.length; i += 1) {
    weights.set(poolIds[i], 1 + (EXPOSURE_WEIGHT_RATIO - 1) * ((max - values[i]) / span));
  }
  return weights;
}

/** Источник случайности: возвращает число из полуинтервала [0, 1). */
export type RandomFn = () => number;

/** Минимальный контракт отбираемого элемента. */
export interface Identified {
  id: string;
}

/**
 * Взвешенная выборка БЕЗ ВОЗВРАЩЕНИЯ методом ключей (FR-15).
 *
 * Каждому элементу назначается ключ `U^(1/w)`, где `U` — случайное число из (0, 1); берутся `k`
 * элементов с наибольшим ключом. Вероятность попасть в выборку растёт с весом, но не становится
 * единицей: отбор остаётся статистическим, а не превращается в сортировку по счётчику.
 *
 * При равных весах метод статистически неотличим от равномерного перемешивания — это и есть
 * механизм деградации (FR-16/FR-17): отдельной ветки «поправка выключена» в коде нет.
 *
 * @param pool - Пул элементов, из которого идёт отбор.
 * @param k - Сколько элементов взять; больше размера пула — вернётся весь пул.
 * @param weights - Карта «id -> вес»; отсутствие ключа означает вес 1.
 * @param rnd - Источник случайности (в тестах — воспроизводимый).
 * @returns Отобранные элементы в порядке убывания ключа.
 */
export function weightedPick<T extends Identified>(
  pool: T[],
  k: number,
  weights: Map<string, number>,
  rnd: RandomFn,
): T[] {
  if (pool.length === 0 || k <= 0) return [];
  const keyed = pool.map((item) => {
    const w = weights.get(item.id) ?? 1;
    // Ровно ноль дал бы нулевой ключ при ЛЮБОМ весе — такой элемент всегда оказывался бы
    // последним независимо от того, насколько он свежий. Сдвигаем в открытый интервал.
    const u = Math.min(Math.max(rnd(), Number.EPSILON), 1 - Number.EPSILON);
    return { item, key: Math.pow(u, 1 / w) };
  });
  keyed.sort((a, b) => b.key - a.key);
  return keyed.slice(0, k).map((x) => x.item);
}
